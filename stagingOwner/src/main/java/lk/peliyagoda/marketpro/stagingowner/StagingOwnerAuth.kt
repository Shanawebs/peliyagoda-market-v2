            conn.setRequestProperty("Authorization","Bearer "+token)
            conn.setRequestProperty("Content-Type","application/json")
            conn.setRequestProperty("Accept","application/json")
            conn.doOutput=true
            conn.outputStream.use {
                it.write(payload.toString().toByteArray(Charsets.UTF_8))
            }
            if(conn.responseCode!=200)
                throw AuthException("Staging Server denied proof ("+conn.responseCode+").")
            val data=conn.inputStream.use { input ->
                val out=ByteArrayOutputStream()
                val buffer=ByteArray(1024)
                while(true) {
                    val n=input.read(buffer)
                    if(n<0)break
                    if(out.size()+n>8192)
                        throw AuthException("Server response too large.")
                    out.write(buffer,0,n)
                }
                out.toByteArray()
            }
            return JSONObject(String(data,Charsets.UTF_8))
        }catch(e:AuthException){
            throw e
        }catch(_:IOException){
            throw AuthException("Staging Server connection failed.")
        }finally {
            conn.disconnect()
        }
    }

    /** No factor enrollment or modification; only preverified TOTP factors. */
    private fun verifiedFactor(a: JSONArray?): String? {
        if (a == null) return null
        for (i in 0 until a.length()) {
            val f = a.optJSONObject(i) ?: continue
            val type = f.optString("factor_type", f.optString("type"))
            val status = f.optString("status")
            val id = f.optString("id")
            if (type == "totp" && status == "verified" && ID_FORMAT.matches(id))
                return id
        }
        return null
    }

    private fun httpFactors(token: String): JSONArray? {
        return try {
            val res = http("/auth/v1/factors", "GET", null, token)
            res.optJSONArray("factors") ?: res.optJSONArray("all")
        } catch (_: AuthException) {
            null
        }
    }

    private fun http(
        path: String, method: String, body: JSONObject?, bearer: String?
    ): JSONObject {
        // No arbitrary URL input. Only these exact Auth endpoints may be called.
        if (!(
            path == "/auth/v1/token?grant_type=password" ||
            path == "/auth/v1/user" ||
            path == "/auth/v1/factors" ||
            Regex("^/auth/v1/factors/[a-f0-9-]{36}/(challenge|verify)$").matches(path)
        )) throw AuthException("Blocked unexpected network endpoint.")
        if (method !in listOf("GET", "POST")) throw AuthException("Blocked HTTP method.")
        val url = URL(ORIGIN + path)
        if (url.protocol != "https" || url.host != "qqiheexpbuzohllugxrk.supabase.co")
            throw AuthException("Blocked non-staging host.")
        val conn = (url.openConnection() as HttpURLConnection)
        try {
            conn.requestMethod = method
            conn.connectTimeout = 10_000
            conn.readTimeout = 12_000
            conn.instanceFollowRedirects = false
            conn.setRequestProperty("apikey", API_KEY)
            conn.setRequestProperty("Accept", "application/json")
            conn.setRequestProperty("Content-Type", "application/json")
            if (bearer != null) conn.setRequestProperty("Authorization", "Bearer $bearer")
            if (method == "POST") {
                conn.doOutput = true
                conn.outputStream.use { stream ->
                    stream.write((body ?: JSONObject()).toString().toByteArray(Charsets.UTF_8))
                }
            }
            val status = conn.responseCode
            if (status !in 200..299) {
                throw AuthException(when(status) {
                    400,401,403 -> "Login/MFA අසාර්ථකයි. Password සහ Code පරීක්ෂා කරන්න."
                    429 -> "බොහෝ උත්සාහ. ටික වෙලාවකින් නැවත උත්සාහ කරන්න."
                    else -> "Staging Auth server ප්‍රතිචාරය ($status)."
                })
            }
            // Bounded read: no untrusted response can allocate unlimited RAM.
            val bytes = conn.inputStream.use { input ->
                val out = ByteArrayOutputStream()
                val chunk = ByteArray(4096)
                while (true) {
                    val count = input.read(chunk)
                    if (count < 0) break
                    if (out.size() + count > MAX_RESPONSE)
                        throw AuthException("Server response too large.")
                    out.write(chunk, 0, count)
                }
                out.toByteArray()
            }
            if (bytes.size > MAX_RESPONSE) throw AuthException("Server response too large.")
            return JSONObject(String(bytes, Charsets.UTF_8))
        } catch (e: AuthException) {
            throw e
        } catch (_: IOException) {
            throw AuthException("Staging network connection අසාර්ථකයි.")
        } catch (_: Exception) {
            throw AuthException("Staging Auth response එක කියවීමට නොහැකි වුණා.")
        } finally {
            conn.disconnect()
        }
    }

    internal class AuthException(message: String): RuntimeException(message)
