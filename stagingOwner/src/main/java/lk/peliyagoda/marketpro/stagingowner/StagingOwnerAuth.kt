    fun verify(code: String): String {
        if (!Regex("^[0-9]{6}$").matches(code))
            throw AuthException("Authenticator ඉලක්කම් 6ම ඇතුළත් කරන්න.")
        val token = aal1 ?: throw AuthException("මුලින් Staging Login කරන්න.")
        val factorId = factor ?: throw AuthException("Authenticator factor එක නැහැ.")
        if (!ID_FORMAT.matches(factorId)) throw AuthException("Authenticator factor ID වලංගු නැහැ.")

        // The challenge must be generated by GoTrue itself, never locally.
        val challenge = http(
            "/auth/v1/factors/$factorId/challenge", "POST", JSONObject(), token
        )
        val challengeId = challenge.optString("id")
        if (!ID_FORMAT.matches(challengeId))
            throw AuthException("Authenticator challenge එක වලංගු නැහැ.")

        val verified = http(
            "/auth/v1/factors/$factorId/verify",
            "POST", JSONObject().put("challenge_id", challengeId).put("code", code),
            token
        )
        val upgraded = verified.optString("access_token")
        if (upgraded.length < 50)
            throw AuthException("MFA verify result එකේ session එකක් නැහැ.")

        // JWT payload is not an independent signature verification. Require a
        // second server read using that same issued token before reporting PASS.
        val claims = try {
            val segments = upgraded.split('.')
            if (segments.size != 3) throw IllegalArgumentException()
            val json = String(Base64.decode(
                segments[1], Base64.URL_SAFE or Base64.NO_WRAP or Base64.NO_PADDING
            ), Charsets.UTF_8)
            JSONObject(json)
        } catch (_: Exception) {
            throw AuthException("MFA session එක හඳුනාගත නොහැක.")
        }
        val sessionId = claims.optString("session_id")
        if (claims.optString("sub") != OWNER_ID ||
            claims.optString("aal") != "aal2" ||
            !ID_FORMAT.matches(sessionId)
        ) throw AuthException("Session එක AAL2 ලෙස verify වී නැහැ.")

        val confirmedUser = http("/auth/v1/user", "GET", null, upgraded)
        if (confirmedUser.optString("id") != OWNER_ID)
            throw AuthException("Supabase Auth session confirmation අසාර්ථකයි.")

        // Keep the upgraded bearer in VOLATILE MEMORY for one immediately
        // subsequent read-only Edge test (max 120 seconds). Never persist it.
        aal1 = null
        factor = null
        aal2TestToken = upgraded
        aal2VerifiedAtMs = System.currentTimeMillis()
        return "PASS ✓ Staging Owner Login + TOTP MFA (AAL2).\n" +
            "Supabase Auth user confirmation passed.\n" +
            "NO device enrolled • NO purchase sync • NO Staff access."
    }

    /**
